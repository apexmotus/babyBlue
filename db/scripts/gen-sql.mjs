// Bundles the SQL files into a TypeScript module so the browser database can apply them.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const dbRoot = path.resolve(import.meta.dirname, "..");
const pgliteDemoSrc = path.resolve(dbRoot, "../packages/pglite-demo/src");
const read = (dir, filter = () => true) =>
  readdirSync(path.join(dbRoot, dir)).filter((f) => f.endsWith(".sql") && filter(f)).sort().map((f) => ({ name: f, sql: readFileSync(path.join(dbRoot, dir, f), "utf8") }));

const files = [...read("local-shims", (f) => f.startsWith("0")), ...read("supabase/migrations"), ...read("local-shims", (f) => f.startsWith("9"))];
mkdirSync(pgliteDemoSrc, { recursive: true });
writeFileSync(
  path.join(pgliteDemoSrc, "sql.generated.ts"),
  `// GENERATED by db/scripts/gen-sql.mjs — do not edit.\nexport const SQL_FILES: { name: string; sql: string }[] = ${JSON.stringify(files)};\n`,
);
console.log(`gen-sql: ${files.length} files`);
