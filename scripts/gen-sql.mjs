// Bundles the SQL files into a TypeScript module so the browser database can apply them.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const read = (dir, filter = () => true) =>
  readdirSync(path.join(root, dir)).filter((f) => f.endsWith(".sql") && filter(f)).sort().map((f) => ({ name: f, sql: readFileSync(path.join(root, dir, f), "utf8") }));

const files = [...read("local", (f) => f.startsWith("0")), ...read("supabase/migrations"), ...read("local", (f) => f.startsWith("9"))];
mkdirSync(path.join(root, "src/local"), { recursive: true });
writeFileSync(
  path.join(root, "src/local/sql.generated.ts"),
  `// GENERATED by scripts/gen-sql.mjs — do not edit.\nexport const SQL_FILES: { name: string; sql: string }[] = ${JSON.stringify(files)};\n`,
);
console.log(`gen-sql: ${files.length} files`);
